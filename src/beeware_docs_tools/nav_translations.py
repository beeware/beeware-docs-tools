"""Translation of navigation titles.

Navigation titles are written into a generated Markdown file (``titles.md``) so
that ``md2po`` extracts them. A navigation title is often the same text as the
heading of the page it links to (for example, "Building documentation"), and
``md2po`` merges duplicate strings, so the two would share a single
translation. Translators may have (and in practice, have) translated them
differently; for example, a shorter title for the navigation.

To keep those translations apart, navigation titles are given their own
message context (``msgctxt "navigation"``), which also tells translators where
the string is used. When a navigation entry has no translation yet, it is
seeded from the translation it would previously have used:

* the link text of an entry from a literate-nav navigation file
  (``[Title]{1}``, from ``SUMMARY.md``); or
* an entry with the same text and no context (a navigation title from before
  this context was introduced, or the matching page heading).
"""

import re

import polib

NAV_CONTEXT = "navigation"

# The generated file containing the navigation titles, relative to the docs
# directory.
TITLES_FILE = "en/titles.md"

# A link, as extracted by md2po from a literate-nav navigation file.
LINK_RE = re.compile(r"^\s*\[(?P<title>.*)\]\s*(\{\d+\}|\([^)]*\))\s*$", re.DOTALL)


def is_titles_source(source: str) -> bool:
    """Is a source reference (from a PO entry) the navigation titles file?"""
    return source == TITLES_FILE or source.endswith(f"/{TITLES_FILE}")


def add_nav_context(po: polib.POFile) -> int:
    """Give the navigation titles in a catalog their own context.

    An entry that is only used by the navigation titles file gets the
    navigation context. An entry that is also used elsewhere (usually as a page
    heading) is split in two: the existing entry keeps the other references,
    and a new entry with the navigation context gets the navigation titles
    file reference.

    :param po: The catalog, as generated by ``md2po``; it is modified in place.
    :returns: The number of navigation entries.
    """
    count = 0
    for entry in list(po):
        if entry.msgctxt or entry.obsolete:
            continue
        titles = [o for o in entry.occurrences if is_titles_source(o[0])]
        if not titles:
            continue
        count += 1
        others = [o for o in entry.occurrences if not is_titles_source(o[0])]
        if others:
            entry.occurrences = others
            po.insert(
                po.index(entry) + 1,
                polib.POEntry(
                    msgid=entry.msgid,
                    msgctxt=NAV_CONTEXT,
                    msgstr="",
                    occurrences=titles,
                ),
            )
        else:
            entry.msgctxt = NAV_CONTEXT
    return count


def previous_translation(previous: polib.POFile, title: str):
    """Find the translation a navigation title had before it had a context.

    :param previous: The catalog to search.
    :param title: The navigation title.
    :returns: A ``(translation, flags)`` tuple, or None if there's no
        translation.
    """
    # A literate-nav link entry is what the navigation actually displayed.
    for entry in previous:
        if entry.obsolete or entry.msgctxt or not entry.msgstr:
            continue
        link = LINK_RE.match(entry.msgid)
        if link and link.group("title") == title:
            translated = LINK_RE.match(entry.msgstr)
            if translated:
                return translated.group("title"), list(entry.flags)

    # Otherwise, an entry with the same text and no context.
    for entry in previous:
        if entry.obsolete or entry.msgctxt or not entry.msgstr:
            continue
        if entry.msgid == title:
            return entry.msgstr, list(entry.flags)

    return None


def seed_nav_translations(po: polib.POFile, previous: polib.POFile) -> list[str]:
    """Fill in untranslated navigation entries from previous translations.

    :param po: The catalog to update, in place.
    :param previous: The catalog containing the previous translations. This
        can be the same catalog as ``po``.
    :returns: The navigation titles that were filled in.
    """
    seeded = []
    for entry in po:
        if entry.obsolete or entry.msgctxt != NAV_CONTEXT or entry.msgstr:
            continue
        if found := previous_translation(previous, entry.msgid):
            entry.msgstr, entry.flags = found
            seeded.append(entry.msgid)
    return seeded
