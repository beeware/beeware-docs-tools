"""Handling of mkdocstrings API directives during translation.

An API directive is a ``::: identifier`` line, optionally followed by an
indented YAML ``options:`` block::

    ::: toga.Button
        options:
          show_root_heading: false

API directives contain only Python identifiers and option settings, so there is
nothing in them to translate. However, the translate-toolkit tools treat the
indented lines as a continuation of the ``:::`` paragraph: ``md2po`` extracts
the whole directive as a single string, and ``po2md`` writes it back on a
single line (``::: toga.Button options: show_root_heading: false``), which
mkdocstrings can't parse, so the translated build fails.

So:

* ``blank_api_blocks`` removes API directives from the copy of the English
  content that ``md2po`` reads, so they never reach the translation catalogs
  (and Weblate); and
* ``restore_api_blocks`` replaces the API directives in the translated content
  generated by ``po2md`` with the English originals.
"""

import re
from pathlib import Path

# The opening line of a fenced code block, and an API directive.
FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})")
API_DIRECTIVE_RE = re.compile(r"^(\s*):::\s+(\S+)")


def api_blocks(lines: list[str]) -> list[tuple[int, int, str, str]]:
    """Find the API directives in Markdown content.

    A directive is a ``::: identifier`` line, followed by any lines that are
    indented further than it (the ``options:`` block), with blank lines allowed
    between them. Directives inside fenced code blocks are ignored.

    :param lines: The lines of the Markdown content.
    :returns: A ``(start, end, indent, identifier)`` tuple for each directive,
        where ``lines[start:end]`` are the lines of the directive, and
        ``indent`` is the indentation of the ``:::`` line.
    """
    blocks = []
    fence = None
    i = 0
    while i < len(lines):
        line = lines[i]
        fence_match = FENCE_RE.match(line)
        if fence:
            # A fence is closed by a bare fence of the same character that is
            # at least as long.
            if (
                fence_match
                and fence_match.group(1)[0] == fence[0]
                and len(fence_match.group(1)) >= len(fence)
                and not line.strip()[len(fence_match.group(1)) :].strip()
            ):
                fence = None
        elif fence_match:
            fence = fence_match.group(1)
        elif directive := API_DIRECTIVE_RE.match(line):
            indent = directive.group(1)
            end = i + 1
            j = i + 1
            while j < len(lines):
                if not lines[j].strip():
                    j += 1
                elif len(lines[j]) - len(lines[j].lstrip()) > len(indent):
                    j += 1
                    end = j
                else:
                    break
            blocks.append((i, end, indent, directive.group(2)))
            i = end
            continue
        i += 1
    return blocks


def _write_lines(path: Path, lines: list[str], newline_at_end: bool) -> None:
    path.write_text(
        "\n".join(lines) + ("\n" if newline_at_end else ""),
        encoding="utf-8",
    )


def blank_api_blocks(md_path: Path) -> list[Path]:
    """Replace every API directive in Markdown content with blank lines.

    The lines are blanked, rather than removed, so that the line numbers
    recorded in the translation catalogs still match the original content.

    :param md_path: The directory containing the Markdown content. Files are
        modified in place, so this must be a copy.
    :returns: The paths (relative to ``md_path``) that were changed.
    """
    changed = []
    for md_file in sorted(md_path.rglob("*.md")):
        text = md_file.read_text(encoding="utf-8")
        lines = text.splitlines()
        blocks = api_blocks(lines)
        if not blocks:
            continue
        for start, end, _, _ in blocks:
            lines[start:end] = [""] * (end - start)
        _write_lines(md_file, lines, text.endswith("\n"))
        changed.append(md_file.relative_to(md_path))
    return changed


def restore_api_blocks(en_md_path: Path, md_path: Path) -> list[Path]:
    """Restore the API directives in translated Markdown content.

    Each API directive in the translated content is replaced with the English
    original with the same identifier (in order of appearance, if an identifier
    is used more than once in a file). The original is re-indented to match the
    translated content, as ``po2md`` normalizes the indentation of list items.

    :param en_md_path: The directory containing the English content.
    :param md_path: The directory containing the translated content.
    :returns: The paths (relative to the content directory) that were changed.
    """
    restored = []
    for en_file in sorted(en_md_path.rglob("*.md")):
        target = md_path / en_file.relative_to(en_md_path)
        if not target.is_file():
            continue

        en_lines = en_file.read_text(encoding="utf-8").splitlines()
        originals = {}
        for start, end, indent, identifier in api_blocks(en_lines):
            originals.setdefault(identifier, []).append((indent, en_lines[start:end]))
        if not originals:
            continue

        text = target.read_text(encoding="utf-8")
        lines = text.splitlines()
        new_lines = []
        position = 0
        for start, end, indent, identifier in api_blocks(lines):
            if not originals.get(identifier):
                continue
            original_indent, original = originals[identifier].pop(0)
            new_lines.extend(lines[position:start])
            new_lines.extend(
                indent + line.removeprefix(original_indent) if line.strip() else ""
                for line in original
            )
            position = end
        new_lines.extend(lines[position:])

        if new_lines != lines:
            _write_lines(target, new_lines, text.endswith("\n"))
            restored.append(en_file.relative_to(en_md_path))
    return restored
